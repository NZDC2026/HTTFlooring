    static void process() throws Exception {
        record Item(UUID id,UUID lease,String type){}
        var items=new ArrayList<Item>();
        try(var c=WorkerMain.connect();var s=c.createStatement();var r=s.executeQuery("select id,lease_token,event_type from platform.claim_outbox(20)")) {
            while(r.next())items.add(new Item(r.getObject(1,UUID.class),r.getObject(2,UUID.class),r.getString(3)));
        }
        for(var item:items) {
            // Same diagnostic sink as legacy: never invent financial or external side effects.
            String error=SUPPORTED.contains(item.type())?null:"No handler registered for event type.";
            WorkerMain.scalar("select platform.finish_outbox(?,?,?)",item.id(),item.lease(),error);
        }
    }
