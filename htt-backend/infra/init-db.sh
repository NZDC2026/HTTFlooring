#!/bin/sh
set -eu
: "${HTT_APP_PASSWORD:?Set HTT_APP_PASSWORD}"
: "${HTT_WORKER_PASSWORD:?Set HTT_WORKER_PASSWORD}"
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=app_password="$HTT_APP_PASSWORD" --set=worker_password="$HTT_WORKER_PASSWORD" <<'SQL'
SELECT format('CREATE ROLE htt_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS PASSWORD %L', :'app_password') \gexec
SELECT format('CREATE ROLE htt_worker LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS PASSWORD %L', :'worker_password') \gexec
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
SQL
