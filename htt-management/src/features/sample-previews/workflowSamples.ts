export interface WorkflowSample {
    title: string;
    paths: RegExp;
    pending: { record: string; detail: string; status: string };
    completed: { record: string; detail: string; status: string };
}

function workflow(
    title: string, paths: RegExp,
    pending: [record: string, detail: string, status: string],
    completed: [record: string, detail: string, status: string],
): WorkflowSample {
    return {
        title, paths,
        pending: { record: pending[0], detail: pending[1], status: pending[2] },
        completed: { record: completed[0], detail: completed[1], status: completed[2] },
    };
}

