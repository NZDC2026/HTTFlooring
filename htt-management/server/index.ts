import env from '../config/environment.cjs';
import { resolve } from 'node:path';
import { createWebApplication } from './app';
const port = Number(env.required('API_PORT'));
if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error('API_PORT must be an integer between 1 and 65535.');
const host = env.required('HOST');
const directory = resolve(env.required('HTT_DATA_DIR'));
const app = createWebApplication({ directory, staticDirectory: resolve('dist-web'), publicOrigin: env.PUBLIC_ORIGIN, secureCookie: env.COOKIE_SECURE === '1' });
app.server.listen(port, host, () => console.log(`HTT web server: http://${host}:${port}\nSQLite data directory: ${directory}`));
for (const signal of ['SIGINT', 'SIGTERM']) process.once(signal, () => { void app.close().then(() => process.exit(0)); });
